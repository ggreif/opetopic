<div class="ui raised segment">
  <h2 class="ui dividing header">Source Universality Coherence</h2>

  <p>
    Our goal in this section is to prove the following:
  </p>

  <div class="ui top attached inverted grey segment">
    <div class="ui header">Proposition</div>
  </div>
  <div class="ui bottom attached segment">
    <p>
      Consider a cell <i>f</i> which is both target universal and
      source universal at a face <i>x</i>.
      Then for any competitor <i>u</i> of <i>x</i> and <i>g</i> a target
      universal cell, it follows that <i>g</i> is source universal at <i>u</i>.
    </p>
  </div>

  <h3 class="ui dividing header">Proof</h3>

  <p>
    First construct the cell <i>α</i> using the source lifting
    property of <i>f</i>.
    Observe that <i>α</i> is target universal by closure.  Now, suppose we
    are given <i>s</i> and <i>t</i>, a lifting problem for the source universality
    of <i>g</i> at <i>u</i>.
  </p>

  <p>
    We first use the universal property of
    <i>f</i> to obtain the cell <i>β</i>.
    Composing <i>β</i> and <i>α</i><sup>−1</sup> we obtain the cell <i>γ</i>.
    From here, cancelling <i>α</i> and <i>α</i><sup>−1</sup> yields <i>f</i> and
    <i>β</i> as the exterior, and <i>t</i> — being universal for this
    configuration — admits the required map to/from <i>g</i> ∘ <i>γ</i>.
  </p>

</div>
