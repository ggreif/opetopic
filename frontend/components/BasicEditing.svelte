<div class="ui raised segment">
  <h2 class="ui dividing header">Basic Editing</h2>

  <p>
    In this section, we describe how to build opetopes graphically
    using the editor interface at the top of this page.
  </p>

  <h3 class="ui dividing header">Extrusion</h3>

  <p>
    The most basic technique is called <em>extrusion</em> and
    consists in enclosing a subtree of cells in a new cell.
  </p>

  <h3 class="ui dividing header">Drop Extrusion</h3>

  <p>
    The opetopic version of <em>degenerate cells</em> are called
    drops.  The editor has a separate facility for inserting drops.
  </p>

  <h3 class="ui dividing header">Prepending a Glob</h3>

  <p>
    While the previous two operations work by inserting new
    space on the target side, it is sometimes convenient to
    insert a new cell on the <em>source</em> side.  We can do
    that by selecting an <em>external</em> cell and asking the
    editor to insert a glob with the chosen cell as its target.
  </p>

</div>
